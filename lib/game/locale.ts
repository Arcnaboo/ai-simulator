let current: Lang = "tr";
const listeners = new Set<() => void>();

function bootstrap() {
  if (typeof window === "undefined") return;
  current = window.localStorage.getItem(LANG_KEY) === "en" ? "en" : "tr";
}

bootstrap();

export function getLang(): Lang {
  return current;
}

export function setLang(next: Lang) {
  current = next;
  if (typeof window !== "undefined") {
    window.localStorage.setItem(LANG_KEY, next);
    document.documentElement.lang = next;
  }
  for (const listener of listeners) listener();
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang, () => "tr" as Lang);
}

function fmt(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
}

export function t(key: UiKey, vars?: Record<string, string | number>): string {
  return fmt(UI[getLang()][key], vars);
}

export function localize(text: string): string {
  if (getLang() === "en") return text;
  return STORY[text] ?? EXTRA[text] ?? text;
}
