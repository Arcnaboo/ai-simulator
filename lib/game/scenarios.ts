import { opt } from "./option";
import type { ChoiceOption, ResponseDef, Scenario } from "./types";

interface Tune {
  help?: number;
  safety?: number;
  engage?: number;
  trust?: number;
  risk?: number;
  hallucination?: boolean;
  pitch?: boolean;
  memory?: string;
}

function reply(
  id: string,
  text: string,
  tokens: number,
  blurb: string,
  tune: Tune,
  options: ChoiceOption[],
): ResponseDef {
  return {
    id,
    text,
    tokens,
    blurb,
    risk: tune.risk ?? 0,
    hallucination: tune.hallucination,
    pitch: tune.pitch,
    helpfulness: tune.help ?? 0,
    safety: tune.safety ?? 0,
    engagement: tune.engage ?? 0,
    trust: tune.trust ?? 0,
    memory: tune.memory,
    options,
  };
}

